"""목적·상호에 섞인 개인정보 제거. 실제 원본에서 본 모양을 합성 이름으로 재현한다."""

import pytest

from deliciousmap.privacy import REDACTED, scrub, scrub_merchant


@pytest.mark.parametrize(
    ("purpose", "expected"),
    [
        ("부의금 지급(특수구조대 홍길동)", "부의금 지급"),
        ("직원(소방위 홍길동) 부의금 지급", "직원 부의금 지급"),
        ("직원 축의금(소방경 홍길동 자녀)지급", "직원 축의금 지급"),
        ("축의금(합성소방서 구조대 소방사 김**) 지급", "축의금 지급"),
        ("직원 경조사 축의금 집행(홍길동)", "직원 경조사 축의금 집행"),
        ("직원 경사 축의금(박○수)", "직원 경사 축의금"),
        ("합성과 직원 한*지 조의금", "합성과 직원 조의금"),
        ("담당 010-1234-5678 연락", "담당 연락"),
        ("직원애사 부의금(홍길동)", "직원애사 부의금"),
        (
            "순직 소방공무원(합성소방서 故 소방경 홍길동) 장례식 근조화환",
            "순직 소방공무원 장례식 근조화환",
        ),
        # 개인 경조사가 아닌 목적의 괄호는 업무 맥락이므로 남긴다. 낱말 속 글자는 경조사가 아니다.
        ("관계자 간담회(합성카페)", "관계자 간담회(합성카페)"),
        ("2026년 월례회 회비 지급(연납)", "2026년 월례회 회비 지급(연납)"),
        ("청사 환경조성 추진 직원 격려(합성팀)", "청사 환경조성 추진 직원 격려(합성팀)"),
        ("정부의 협조 요청 간담회(합성과)", "정부의 협조 요청 간담회(합성과)"),
        ("건축의 날 행사 협의(합성과)", "건축의 날 행사 협의(합성과)"),
    ],
)
def test_personal_details_are_removed_from_purposes(purpose: str, expected: str) -> None:
    assert scrub(purpose) == expected


@pytest.mark.parametrize(
    ("merchant", "purpose", "expected"),
    [
        ("홍길동", "부의금 지급(특수구조대 홍길동)", REDACTED),
        ("홍길순", "직원 애경사 부의금 집행", REDACTED),
        ("김ㅇㅇ", "직원 축의금", REDACTED),
        ("한*지", "직원 조의금 지급", REDACTED),
        ("허 * *", "직원경사 축의금 지급", REDACTED),
        ("박○○", "직원 경조사비 집행", REDACTED),
        # 업소·일반 명칭은 그대로 둔다.
        ("소속직원", "소속 직원 결혼 축의금 집행", "소속직원"),
        ("합성정", "재난상황실 근무자 노고 격려", "합성정"),
        ("합성정", "청사 방호 및 환경조성 추진 직원 격려", "합성정"),
        ("합성정", "정부의 정책 협의 간담회", "합성정"),
        ("합성플라워", "직원 부친상 근조 화환 구입", "합성플라워"),
    ],
)
def test_person_named_as_the_payee_is_redacted(merchant: str, purpose: str, expected: str) -> None:
    assert scrub_merchant(merchant, purpose) == expected
